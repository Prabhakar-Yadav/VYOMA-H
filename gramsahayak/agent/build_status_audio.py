"""One-time build script: synthesizes STATUS_MESSAGES (agent/status_messages.py, itself
generated by build_status_messages.py) through this project's own real production TTS engine
(MMS-TTS, via the real gateway's /tts/load + /tts/infer -- the exact code path a farmer's own
answer audio takes) into short WAV clips, one per (stage/tool, language). Writes
`agent/status_audio/<lang>/<key>.wav`, read at runtime by agent.py's `get_status_audio_path()`
(same graceful-fallback contract as `get_status_message()`).

Why baked-in clips, not a live TTS call per status update: same reasoning as
build_status_messages.py's own docstring -- a status cue exists to show up (now: to be heard)
INSTANTLY the moment a stage/tool starts. A live TTS call per cue would add real synthesis
latency to the exact moment this is meant to mask, working against its own purpose. Synthesize
once, here, offline; play a plain WAV file at runtime (zero model calls, zero real cost per
play) -- this is the concrete build for the 2026-08-14/15 latency investigation's status-audio
idea (play a pre-recorded tool-status clip instead of live TTS, to keep a farmer engaged during
the agent's own real tool-calling latency without adding to it).

Goes through the real gateway (POST /tts/load, POST /tts/infer), not a direct model_loader.py
import -- unlike build_status_messages.py's direct NMTEngine import, MMS-TTS's real synthesis
path (models/mms_tts + api_server/workers/tts_worker.py's chunking/engine-factory logic) is
non-trivial to reproduce correctly outside the worker, and going through the gateway is the
exact same code a real farmer's answer audio runs through -- more faithful, not less, for a
one-time offline build where synthesis latency itself doesn't matter.

Run (GX10 or Jetson, real venv -- needs a real gateway; spawns run_all.py itself if one isn't
already running, same safe reuse-check as test_orchestrated_pipeline.py's own):
    cd gramsahayak && venv/bin/python3 agent/build_status_audio.py
"""
import base64
import os
import subprocess
import sys
import time

import requests

_AGENT_DIR = os.path.dirname(os.path.abspath(__file__))
_ROOT_DIR = os.path.dirname(_AGENT_DIR)
sys.path.insert(0, _ROOT_DIR)

from api_server import config  # noqa: E402
from agent.status_messages import STATUS_MESSAGES  # noqa: E402

GATEWAY = f"http://{config.GATEWAY_HOST}:{config.GATEWAY_PORT}"
OUT_ROOT = os.path.join(_AGENT_DIR, "status_audio")

# 2026-08-15: was {en, hi, ta, ml} only -- matched build_status_messages.py's OWN prior
# stale scope (see that script's real 2026-08-15 fix), not the real device. This device's
# real, complete two-way-voice set is English + config.WORKERS["asr"]["languages"] (12
# Indic languages, expanded 2026-08-14) = 13 -- built from the same config source as the
# text build now, so audio can't drift out of sync with text/ASR again the way it just did.
# config.MMS_TTS_LANGUAGE_NAME_TO_CODE has a couple of extra entries (Dogri, Odia) with real
# MMS-TTS coverage but no ASR checkpoint on this device -- deliberately excluded here, same
# as build_status_messages.py, since a status *cue* for a language this device can't actually
# hear a farmer speak in has no real use.
# 2026-08-16: STATUS_BUILD_LANGUAGES env override (comma-separated codes, "en" implied if
# missing) -- same real reason as build_status_messages.py's own override: "get the Hi and EN
# one created first... implement in jetson and gx10... do the others in parallel while we
# test". Each language writes to its own status_audio/<lang>/ folder independently, so a
# scoped run here never touches or loses any other language's already-built clips -- no merge
# logic needed the way the text build's single output file required.
_lang_override = os.environ.get("STATUS_BUILD_LANGUAGES")
if _lang_override:
    _override_codes = {c.strip() for c in _lang_override.split(",") if c.strip()} | {"en"}
    _full_names = {"en": "English", **{
        code: name for name, code in config.MMS_TTS_LANGUAGE_NAME_TO_CODE.items()
        if code in config.WORKERS["asr"]["languages"]
    }}
    TTS_LANGUAGE_NAMES = {code: name for code, name in _full_names.items() if code in _override_codes}
else:
    TTS_LANGUAGE_NAMES = {"en": "English", **{
        code: name for name, code in config.MMS_TTS_LANGUAGE_NAME_TO_CODE.items()
        if code in config.WORKERS["asr"]["languages"]
    }}


def wait_for_gateway(timeout=20.0):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            if requests.get(f"{GATEWAY}/health", timeout=1.0).status_code == 200:
                return True
        except requests.exceptions.RequestException:
            pass
        time.sleep(0.3)
    return False


def _safe_filename(key: str, variant_index: int) -> str:
    """"tool:analyze_photo", 0 -> "tool_analyze_photo_v0.wav" -- ':' isn't safe in a filename
    on every real target filesystem this device might use. `_v{index}` (2026-08-16) since each
    key is now a LIST of phrasings, not one fixed string -- see agent.py's
    get_status_audio_path() for how variant_index is chosen at runtime."""
    return f"{key.replace(':', '_')}_v{variant_index}.wav"


def main():
    # Same real incident/fix as test_orchestrated_pipeline.py's main() -- check reachability
    # BEFORE spawning, only own+teardown a gateway this run didn't find already running, so a
    # bad exit here can't tear down someone else's live session.
    we_own_the_gateway = not wait_for_gateway(timeout=1.0)
    gateway_proc = None
    if we_own_the_gateway:
        print("[BUILD] no gateway found -- spawning our own run_all.py")
        gateway_proc = subprocess.Popen(
            [sys.executable, "run_all.py"], cwd=os.path.join(_ROOT_DIR, "api_server")
        )
    else:
        print("[BUILD] *** a gateway is already running -- reusing it, NOT spawning or "
              "tearing down our own ***")

    try:
        if not wait_for_gateway():
            print("gateway did not become healthy in time", file=sys.stderr)
            return 1

        tts_batch_size = config.WORKERS["tts"]["default_batch_size"]
        total_written = 0
        total_bytes = 0

        for lang, tts_name in TTS_LANGUAGE_NAMES.items():
            out_dir = os.path.join(OUT_ROOT, lang)
            os.makedirs(out_dir, exist_ok=True)

            print(f"\n[BUILD] === {lang} ({tts_name}) === loading...")
            r = requests.post(f"{GATEWAY}/tts/load", params={"language": tts_name}, timeout=180)
            r.raise_for_status()

            for key, entry in STATUS_MESSAGES.items():
                # Same graceful fallback as agent.py's get_status_message(): missing text for
                # this language falls back to that entry's own English variants, never a
                # crash/gap. Each key is now a LIST of phrasings (2026-08-16) -- one real
                # synthesis + one real file per variant, not one per key.
                variants = entry.get(lang) or entry["en"]
                for v_idx, text in enumerate(variants):
                    r = requests.post(
                        f"{GATEWAY}/tts/infer",
                        json={"text": text, "language": tts_name, "batch_size": tts_batch_size},
                        timeout=180,
                    )
                    r.raise_for_status()
                    audio_bytes = base64.b64decode(r.json()["audio_base64"])

                    out_path = os.path.join(out_dir, _safe_filename(key, v_idx))
                    with open(out_path, "wb") as f:
                        f.write(audio_bytes)
                    total_written += 1
                    total_bytes += len(audio_bytes)
                    print(f"[BUILD]   {key} [{lang}] v{v_idx}: \"{text}\" -> {out_path} ({len(audio_bytes)} bytes)")

            print(f"[BUILD] === {lang} done, unloading ===")
            requests.post(f"{GATEWAY}/tts/unload", timeout=30)

        print(f"\n[BUILD] wrote {total_written} clips ({total_bytes / 1e6:.1f}MB total) under {OUT_ROOT}/")
        return 0
    finally:
        if we_own_the_gateway and gateway_proc is not None:
            print("[BUILD] tearing down the gateway we spawned...")
            gateway_proc.terminate()
            try:
                gateway_proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                gateway_proc.kill()


if __name__ == "__main__":
    sys.exit(main())
